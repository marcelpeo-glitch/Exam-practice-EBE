export interface Plural {
  zero?: string;
  one?: string;
  two?: string;
  few?: string;
  many?: string;
  other: string;
}

type English = typeof UI_EN;
export type UiKey = keyof English;
/** Keys whose value is a plain string. */
export type TextKey = { [K in UiKey]: English[K] extends string ? K : never }[UiKey];
/** Keys whose value is a plural object. */
export type PluralKey = Exclude<UiKey, TextKey>;
/** The shape every language file must have: exactly the English keys, with the same kind of value. */
export type UiDict = { [K in UiKey]: English[K] extends string ? string : Plural };
